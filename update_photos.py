#!/usr/bin/env python3
"""Scan the filter folders and write photos.js, the list of photos the site shows.

Run this after adding, removing or renaming photos:
    python3 update_photos.py
(or double-click "Update photos.command" in Finder)
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))

# Filter folders, in the order they appear on the site, plus FOTOS
# (shown when none of the filters has photos yet)
FOLDERS = ["Selects", "All", "2021", "2022", "2023", "2024", "2025", "2026", "FOTOS"]
IMAGE_TYPES = (".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif")


def natural_key(name):
    # Sort "img2" before "img10"
    return [int(part) if part.isdigit() else part.lower() for part in re.split(r"(\d+)", name)]


photos = {}
for folder in FOLDERS:
    path = os.path.join(ROOT, folder)
    files = os.listdir(path) if os.path.isdir(path) else []
    photos[folder] = sorted(
        (f for f in files if f.lower().endswith(IMAGE_TYPES) and not f.startswith(".")),
        key=natural_key,
    )

with open(os.path.join(ROOT, "photos.js"), "w", encoding="utf-8") as out:
    out.write("// Generated by update_photos.py: do not edit by hand\n")
    out.write("const PHOTOS = " + json.dumps(photos, indent=2, ensure_ascii=False) + ";\n")

for folder, files in photos.items():
    print(f"{folder:>8}: {len(files)} photo(s)")
print("Wrote photos.js")
